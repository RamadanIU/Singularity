def v_prep(word: str) -> str:
    """Предлог «в»/«во»: во Владивостоке, во Владимире, но в Волгограде."""
    w = word.lower()
    return "во" if len(w) > 1 and w[0] in "вф" and w[1] not in "аеёиоуыэюя" else "в"


