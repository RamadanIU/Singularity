# Вопросы о самом пользователе: их нельзя ставить «помехой» между фактом и вопросом о нём
_ABOUT_USER = re.compile(r"(?<!\w)(мне|меня|мой|моя|моё|мое|мою|моего|моих|мои|я|зовут)(?!\w)", re.IGNORECASE)


# «Небрежный ввод»: на телефоне пишут без заглавных и без знаков, добавляют «слушай», «а». Смысл тот же —
# модель должна отвечать так же. Обёртки нарочно НЕ совпадают с отложенными проверочными формулировками.
QUESTION_WRAPS = ["Слушай, ", "А ", "Слушай, а ", "Интересно, ", "Ну, ", "Вопрос: ", "Эй, ", "Слушай, скажи, "]
NO_AUG_SRC = ("шаблон:повтор", "шаблон:бессмыслица", "шаблон:чужой язык", "ручные:язык")


def casual(text: str, rng: random.Random) -> str:
    """Одна реплика пользователя в «небрежном» виде (смысл не меняется)."""
    t = text
    if t.endswith("?") and rng.random() < 0.35:
        w = rng.choice(QUESTION_WRAPS)
        if not (len(t) > 1 and t[1:2].isupper()):          # «США», «ИИ» не трогаем
            t = t[:1].lower() + t[1:]
        t = w + t
    r = rng.random()
    if r < 0.5:
        t = t[:1].lower() + t[1:]
    if rng.random() < 0.5:
        t = t.rstrip(".!?")
    if rng.random() < 0.1:
        t = t.replace("ё", "е").replace("Ё", "Е")
    return t or text


def augment(rows: List[dict], rng: random.Random, p: float) -> int:
    """С вероятностью p каждая реплика пользователя становится «небрежной». Возвращает, сколько изменено."""
    n = 0
    for r in rows:
        if r["src"].endswith(NO_AUG_SRC) or r["src"] in NO_AUG_SRC:
            continue
        for t in r["turns"]:
            if t[0] == "user" and rng.random() < p:
                new = casual(t[1], rng)
                n += int(new != t[1])
                t[1] = new
    return n


def mined_rows(mined: List[dict]) -> List[dict]:
    return [row([("user", m["q"]), ("bot", m["a"])], "субтитры") for m in mined]


COMPOSE_MIX = {"субтитры": 0.4, "ручные": 0.3, "шаблон": 0.3}


def compose(rng: random.Random, pool: List[dict], n: int) -> List[dict]:
    """
    Склейка 2–4 независимых обменов репликами: модель учится отвечать на ПОСЛЕДНИЙ вопрос, а не на
    первый. Источник каждой реплики выбирается по долям COMPOSE_MIX (иначе склейки состояли бы почти
    из одних шаблонов или одних субтитров).
    """
    groups: Dict[str, List[dict]] = {}
    for r in pool:
        groups.setdefault(r["src"].split(":")[0], []).append(r)
    names = [g for g in COMPOSE_MIX if groups.get(g)]
    weights = [COMPOSE_MIX[g] for g in names]
    out = []
    for _ in range(n):
        parts = [rng.choice(groups[rng.choices(names, weights)[0]]) for _ in range(rng.randint(2, 4))]
        turns: List[Turn] = []
        for p in parts:
            turns += [tuple(t) for t in p["turns"]]
        out.append(row(turns, "склейка:" + parts[-1]["src"], parts[-1].get("check")))
    return out


def build_dataset(mined: List[dict], seed: int = 11, n_compose: int = 30000, mined_val: int = 1000,
                  scale: float = 1.0, augment_p: float = 0.3, context_skills: bool = True,
                  context_scale: float = 1.0) -> Dict[str, List[dict]]:
    """Старая часть (как у нынешней mini2) собирается тем же генератором случайных чисел, что и раньше;
    навыки «несколько вопросов» и «контекст» (context_skills) — отдельным, ПОСЛЕ неё: старая часть набора и
    1 431 прежняя задача остаются в точности теми же."""
    rng = random.Random(seed)
    singles, multis = load_seeds()
    train, val, probes, open_eval = [], [], [], []
    choice_src: List[Tuple[str, str, str]] = []          # (вопрос, ответ, источник) для выбора из 5

    # 1) ручные однократные: последняя формулировка (если их >= 4) отложена для проверки
    seed_train_single: List[dict] = []
    for b in singles:
        qs = b.questions
        held = qs[-1] if len(qs) >= 4 else None
        train_qs = qs[:-1] if held else qs
        check = chk(*b.check, none=b.none) if b.check else None
        for qi, q in enumerate(train_qs):
            for r in range(SEED_REPEAT * TAG_WEIGHT.get(b.tag, 1)):
                a = b.answers[(qi + r) % len(b.answers)]
                rr = row([("user", q), ("bot", a)], "ручные:" + b.tag, check)
                train.append(rr)
                if r == 0:
                    seed_train_single.append(rr)
        if held:
            val.append(row([("user", held), ("bot", b.answers[0])], "ручные:" + b.tag, check))
            open_eval.append(row([("user", held), ("bot", b.answers[0])], "ручные:" + b.tag, check))
            choice_src.append((held, b.answers[0], "ручные (новая формулировка)"))
            if check:
                probes.append({"cat": "ручные:" + b.tag, "turns": [["user", held]], "check": check})
    # 2) ручные многоходовые
    for tag, turns in multis:
        for _ in range(MULTI_REPEAT):
            train.append(row(turns, "ручные:" + tag))

    # 3) добытые из субтитров
    m_rows = mined_rows(mined)
    m_val, m_train = m_rows[:mined_val], m_rows[mined_val:]
    train += m_train
    val += m_val[: mined_val // 2]
    for r in m_val:
        choice_src.append((r["turns"][0][1], r["turns"][1][1], "субтитры (новые пары)"))
    open_eval += m_val[:100]

    # 4) шаблоны: «помехи» между фактом и вопросом — короткие обмены из ручных и добытых пар
    filler = [[tuple(t) for t in r["turns"]] for r in seed_train_single + m_train[:20000]
              if len(r["turns"]) == 2 and not _ABOUT_USER.search(r["turns"][0][1])]
    g = Gen(rng, filler)
    opp = _opposites_table()
    defs = _table(DEFINITIONS)
    people = _table(PEOPLE)
    phrases_train = [r["turns"][1][1] for r in m_train[:5000] if 2 <= len(r["turns"][1][1].split()) <= 6] or \
        [b.answers[0] for b in singles if len(b.answers[0].split()) <= 6]
    phrases_test = [r["turns"][1][1] for r in m_val if 2 <= len(r["turns"][1][1].split()) <= 6] or phrases_train[:20]
    extra = {"opposite": (opp,), "definition": (defs,), "person": (people,), "opinion": (_table(TOPICS),),
             "howto": (_table(HOWTO),), "new_word_reference": (defs,), "new_word_unknown": (defs,)}
    template_train: List[dict] = []
    for name, n_train, n_test in TEMPLATE_PLAN:
        fn = getattr(g, name)
        for i in range(int(n_train * scale)):
            if name in ("gibberish", "foreign"):
                template_train.append(fn())
            elif name == "repeat":
                template_train.append(fn(True, phrases_train))
            else:
                template_train.append(fn(True, *extra.get(name, ())))
        for i in range(n_test):
            if name == "repeat":
                p = fn(False, phrases_test)
            else:
                p = fn(False, *extra.get(name, ()))
            val.append(p) if i % 4 == 0 else None
            probes.append({"cat": p["src"], "turns": p["turns"][:-1], "check": p["check"]})
    train += template_train

    # 5) склейки из всего, что есть (кроме длинных многоходовых)
    pool = [r for r in train if len(r["turns"]) == 2 and r["src"] != "шаблон:имя"
            and not (r["src"] == "ручные:не знаю" and _ABOUT_USER.search(r["turns"][0][1]))]
    train += compose(rng, pool, int(n_compose * scale))
    train = [{**r, "turns": [list(t) for t in r["turns"]]} for r in train]   # копии: склейки делят реплики
    augment(train, rng, augment_p)
    rng.shuffle(train)
    # Проверка на «небрежном» вводе: те же отложенные задачи, но без заглавных и знаков препинания
    sloppy_rng = random.Random(seed + 1)
    for p in list(probes)[::3]:
        if p["cat"].endswith(NO_AUG_SRC) or p["cat"].startswith(NEW_SKILL_SRC):
            continue
        turns = [list(t) for t in p["turns"]]
        last = turns[-1][1]
        turns[-1][1] = (last[:1].lower() + last[1:]).rstrip(".!?")
        if turns[-1][1] != last:
            probes.append({"cat": "небрежный ввод", "turns": turns, "check": p["check"], "from": p["cat"]})
    del sloppy_rng

    # Выбор из 5: правильный ответ + 4 ответа на другие вопросы; правильный вопрос + 4 других
    choice = []
    by_src: Dict[str, List[Tuple[str, str]]] = {}
    for q, a, s in choice_src:
        by_src.setdefault(s, []).append((q, a))
    for s, pairs in by_src.items():
        for i, (q, a) in enumerate(pairs):
            others = [p for j, p in enumerate(pairs) if j != i and p[1].lower() != a.lower() and p[0].lower() != q.lower()]
            if len(others) < 8:
                continue
            pick = rng.sample(others, 8)
            choice.append({"src": s, "context": [["user", q]], "answer": a,
                           "distractors": [p[1] for p in pick[:4]],
                           "other_contexts": [[["user", p[0]]] for p in pick[4:]]})
    rng.shuffle(choice)
    # Защита от утечки: отложенная ручная формулировка могла совпасть с фразой из шаблонов (например,
    # «Какой у меня возраст?»). Такие вопросы из проверки убираем — проверяем только то, чего модель не видела.
    seen = {t[1] for r in train for t in r["turns"] if t[0] == "user"}

    def unseen(turns) -> bool:
        return turns[-1][1] not in seen

    probes = [p for p in probes if not p["cat"].startswith("ручные") or unseen(p["turns"])]
    probes = [p for p in probes if not (p["cat"] == "небрежный ввод" and p["from"].startswith("ручные"))
              or unseen(p["turns"])]
    choice = [c for c in choice if not c["src"].startswith("ручные") or unseen(c["context"])]
    open_eval = [r for r in open_eval if not r["src"].startswith("ручные") or unseen(r["turns"][:-1])]
    out = {"sft_train": train, "sft_val": val, "probes": probes, "choice": choice, "open_eval": open_eval}
    if not context_skills:
        return out
    # Навыки А и Б: свой генератор случайных чисел — старая часть выше от них не зависит
    crng = random.Random(seed + 7919)
    ctx = build_context_skills(crng, filler, scale=scale * context_scale, augment_p=augment_p)
    seen_all = seen | {t[1] for r in ctx["train"] for t in r["turns"] if t[0] == "user"}
    new_probes = [p for p in ctx["probes"] if p["turns"][-1][1] not in seen_all]
    merged = train + ctx["train"]
    crng.shuffle(merged)
    out.update(sft_train=merged, probes=probes + new_probes, sft_val_context=ctx["val"])
    return out


def describe(rows: List[dict]) -> Dict[str, object]:
    by_src = Counter(r["src"].split(":")[0] for r in rows)
    by_tag = Counter(r["src"] for r in rows)
    turns = [len(r["turns"]) for r in rows]
    return {"dialogues": len(rows), "by_source": dict(by_src.most_common()),
            "top_tags": dict(by_tag.most_common(40)),
            "mean_turns": round(sum(turns) / max(1, len(turns)), 2),
            "with_check": sum(1 for r in rows if r.get("check"))}
