    # ---------- смена темы: вопрос-продолжение относится к НОВОЙ теме
    def ctx_topic_shift(self, train: bool) -> dict:
        r = self.rng.random()
        w1 = self._work(train)
        if r < 0.6:                            # два произведения подряд — вопрос о последнем
            turns, _, _, _ = self._work_dialogue(train, self.rng.randint(0, 1), w=w1)
            for _ in range(10):
                w2 = self._work(train)
                if w2["title"] != w1["title"] and not _overlap(w1["title"], w2["plot"][1]) \
                        and not _overlap(w1["title"], w2["feature"][1]):
                    break
            shift = self.pick(["Ладно, давай о другом. ", "А ещё ", "Кстати, ", "Знаешь, ", ""])
            m = self._mention(w2, train)
            msg = shift + (low(m) if shift in ("А ещё ", "Кстати, ", "Знаешь, ") else m)
            turns += [("user", msg), ("bot", self.pick(WORK_REACTIONS))]
            fill = self._fill(w2["g"], w2["kind"])
            qk = self.pick(["recall_about", "would", "opinion"])
            q = self._q(qk, train, fill)
            self._last_q = q
            a, keys, _ = self._answer_work(w2, qk, ["about"], None)
            turns += [("user", q), ("bot", a)]
            return row(turns, "навык:контекст: смена темы", self._work_check(w2, keys, q, none=[w1["title"]]))
        if r < 0.8:                            # произведение → еда
            turns, _, _, _ = self._work_dialogue(train, 1, w=w1)
            food = self._food(train)
            return row(turns + [tuple(t) for t in food["turns"]], "навык:контекст: смена темы",
                       {**food["check"], "none": food["check"].get("none", []) + [w1["title"]]})
        # бот назвал известное → пользователь спрашивает о другом → бот называет другое → вопрос о нём
        first = self.ctx_famous_bot(train, 1)
        second = self.ctx_famous_bot(train, 1)
        k1 = first["check"]["all"][0]["any"]
        k2 = second["check"]["all"][0]["any"]
        if set(k1) == set(k2) or any(_overlap(second["turns"][-1][1], w) for w in k1):
            return self.ctx_topic_shift(train)
        turns = [tuple(t) for t in first["turns"]] + [tuple(t) for t in second["turns"]]
        c = second["check"]
        return row(turns, "навык:контекст: смена темы", {**c, "none": c.get("none", []) + k1})

    # ---------- вопрос-продолжение без темы: переспросить, а не выдумывать
    def ctx_no_topic(self, train: bool) -> dict:
        turns: List[Turn] = []
        r = self.rng.random()
        if r < 0.3:
            turns += self.pick([[("user", "Привет!"), ("bot", "Привет! Как дела?")],
                                [("user", "Привет! Как дела?"), ("bot", "Привет! Хорошо, спасибо. А у тебя?")],
                                [("user", "Добрый вечер!"), ("bot", "Добрый вечер! Чем займёмся?")]])
        elif r < 0.5 and train:
            turns += self.distract(1)
        if train and self.rng.random() < 0.6:
            # те же вопросы-продолжения, что в диалогах с темой: без темы на них нужно переспросить
            q = self.pick(UNCLEAR_Q_FROM_FOLLOWUPS)
        else:
            q = self.pick(UNCLEAR_Q_TRAIN if train else UNCLEAR_Q_TEST)
        q = self._wrap(q, train)                     # те же обёртки, что у вопросов с темой
        turns += [("user", q), ("bot", self.pick(UNCLEAR_ANSWERS))]
