def _opposites_table() -> Dict[str, set]:
    t: Dict[str, set] = {}
    for pair in OPPOSITE_PAIRS:
        a, b = pair.split("-")
        t.setdefault(a, set()).add(b)
        t.setdefault(b, set()).add(a)
    return t


def _table(text: str) -> List[Tuple[str, ...]]:
    return [tuple(x.strip() for x in ln.split("|")) for ln in text.strip().splitlines() if ln.strip()]


