def past(verb_stem_m: str, g: str) -> str:
    """Прошедшее время по роду: «вышел» → вышел / вышла / вышло / вышли; «был» → был / была / было / были."""
    if verb_stem_m.endswith("ел"):
        base = verb_stem_m[:-2] + "л"
        return {"м": verb_stem_m, "ж": base + "а", "с": base + "о", "мн": base + "и"}[g]
    return verb_stem_m + PRONOUNS[g]["past"]


