    def _food(self, train: bool, src: str = "навык:контекст: еда, питомцы, места") -> dict:
        nom, acc, prep, g, key, allowed = self.pick(FOODS_CTX_TRAIN if train else FOODS_CTX_TEST)
        sweet = self.pick(list(allowed)) == "с"
        qk = self.pick(["sweet", "filling"])
        # «сладкий ли?» о начинке, которой модель не видела, — проверка знаний, а не контекста: в проверке такой
        # вопрос — только о знакомых начинках (новое — блюдо), а «с чем он?» — о новых начинках
        known = train or qk == "sweet"
        fill, fkey = self.pick((FILLINGS_SWEET_TRAIN if known else FILLINGS_SWEET_TEST) if sweet
                               else (FILLINGS_SAVORY_TRAIN if known else FILLINGS_SAVORY_TEST))
        p = self._fill(g)
        was = past("был", g)
        msg = self.pick(FOOD_MENTIONS_TRAIN if train else FOOD_MENTIONS_TEST).format(acc=acc, nom=nom, fill=fill, был=was)
        turns: List[Turn] = [("user", msg), ("bot", self.pick(["Звучит вкусно!", "Вкусно!", "Ммм, здорово!",
                                                                  "Как вкусно! Понравилось?"]))]
        if turns[-1][1].endswith("?"):
            turns.append(("user", self.pick(["Очень!", "Да, было вкусно."]) + " " +
                          self._q(qk, train, {**p, "sweet": p["sweet"]}, FOOD_Q)))
            q = turns[-1][1]
        else:
            q = self._q(qk, train, {**p, "sweet": p["sweet"]}, FOOD_Q)
            turns.append(("user", q))
        Nom = cap(nom)
        if "сладк" in q:
            a = f"{'Да' if sweet else 'Нет'}, {nom} {fill} — {'' if sweet else 'не '}сладк{p['sweet']}."
            pol = chk("сладк", none=["не сладк"]) if sweet else chk("не сладк", "несладк")
            c = chk_all(chk(*key.split(",")), chk(*fkey.split(",")), pol)
        else:
            a = f"{Nom} {was} {fill}."
            c = chk_all(chk(*key.split(",")), chk(*fkey.split(",")), none=self._echo(q))
        turns.append(("bot", a))
        return row(turns, src, c)

