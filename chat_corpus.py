class Gen:
    """Генераторы шаблонных диалогов: train=True — обучающие значения/формулировки, False — отложенные."""

    def __init__(self, rng: random.Random, filler: List[List[Turn]]):
        self.rng = rng
        self.filler = filler          # короткие посторонние обмены репликами (для «помехи» между фактом и вопросом)

    def pick(self, xs):
        return self.rng.choice(xs)

    def distract(self, k_max: int = 3) -> List[Turn]:
        out: List[Turn] = []
        for _ in range(self.rng.randint(0, k_max)):
            out += self.pick(self.filler)
        return out

    # ---------- память: имя
    def name_memory(self, train: bool) -> dict:
        n = self.pick(NAMES_TRAIN if train else NAMES_TEST)
        intro = self.pick(["Меня зовут {n}.", "Привет! Меня зовут {n}.", "Я {n}.", "Привет, я {n}.", "Моё имя — {n}.",
                           "Зови меня {n}.", "Будем знакомы, я {n}.", "Давай знакомиться: я {n}."]
                          if train else ["Здравствуй, меня зовут {n}.", "Меня зовут {n}.", "Привет, я {n}."]).format(n=n)
        greet = self.pick(["Приятно познакомиться, {n}!", "Привет, {n}! Рад знакомству.", "Очень приятно, {n}! Как дела?",
                           "Здравствуй, {n}! Чем займёмся?"]).format(n=n)
        ask = self.pick(["Как меня зовут?", "Ты помнишь, как меня зовут?", "Как моё имя?", "Напомни, как меня зовут.",
                         "Ты не забыл моё имя?", "Как меня зовут, помнишь?", "А как меня зовут?"]
                        if train else ["Скажи моё имя.", "Как меня зовут?"])
        ans = self.pick(["Тебя зовут {n}.", "Ты {n}.", "Конечно помню: тебя зовут {n}.", "Твоё имя — {n}."]).format(n=n)
        if self.rng.random() < 0.25:     # всё в одной реплике
            return row([("user", f"{intro} {ask}"), ("bot", ans)], "шаблон:имя", chk(n))
        turns = [("user", intro), ("bot", greet)] + self.distract() + [("user", ask), ("bot", ans)]
        return row(turns, "шаблон:имя", chk(n))

    def name_correction(self, train: bool) -> dict:
        names = NAMES_TRAIN if train else NAMES_TEST
        n1, n2 = self.rng.sample(names, 2)
        turns = [("user", f"Меня зовут {n1}."), ("bot", f"Приятно познакомиться, {n1}!"),
                 ("user", self.pick(["Ой, нет, меня зовут {n}.", "Извини, на самом деле меня зовут {n}.",
                                     "Вообще-то меня зовут {n}.", "Нет, на самом деле я {n}."]).format(n=n2)),
                 ("bot", self.pick(["Извини, {n}! Теперь запомнил.", "Понял, {n}! Буду знать."]).format(n=n2))]
        turns += self.distract(2) + [("user", self.pick(["Как меня зовут?", "Напомни, как меня зовут."])),
                                     ("bot", f"Тебя зовут {n2}.")]
        return row(turns, "шаблон:исправление", chk(n2, none=[n1]))

