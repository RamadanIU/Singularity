def _overlap(a: str, keys: str) -> bool:
    """Есть ли у ключей проверки общие слова с текстом (тогда факт засчитывался бы по одному названию)."""
    t = _norm(a)
    return any(k and re.search(r"(?<!\w)" + re.escape(k), t) for k in (_norm(x) for x in keys.split(",")))


def _unclear_from_followups() -> List[str]:
    """Обучающие вопросы-продолжения во всех родах — для примеров «без темы» (переспросить)."""
    out = set()
    for g, p in PRONOUNS.items():
        for kind in WORK_KINDS.values():
            fill = {**p, "Nom": cap(p["nom"]), "Он": cap(p["nom"]), "он": p["nom"], "вышел": past("вышел", g),
                    "inf": kind["inf"], "cond": kind["cond"],
                    "obj": (kind["obj_pre"] + p["obj_v"]) if kind["obj_pre"] else p["acc"]}
            for name in ("about", "hero", "interesting", "why", "recommend", "old", "recall_about", "would"):
                out |= {q.format(**fill) for q in FOLLOWUP_Q[name][0]}
            out |= {q.format(**fill) for q in PET_Q["color"][0] + FOOD_Q["sweet"][0] + FOOD_Q["filling"][0]}
    out |= set(CITY_Q["loc"][0] + CITY_Q["sight"][0])
    return sorted(out)


class ContextGen(Gen):
    """Генераторы навыков А и Б. train=True — обучающие значения и формулировки, False — отложенные."""

    def __init__(self, rng: random.Random, filler: List[List[Turn]]):
        super().__init__(rng, filler)
        self.opp = _opposites_table()
        self._last_q = ""
        self._said: set = set()

    @staticmethod
    def _yes_old(old: bool, q: str, tail: str) -> str:
        """«А он старый?» / «Он давно вышел?» — да, если старый; «Он новый?» — да, если новый;
        «старое или новое?» — без «да/нет»."""
        if " или " in q:
            return cap(tail)
        yes = old if ("стар" in q or "давно" in q) else not old
        return f"{'Да' if yes else 'Нет'}, {tail}"

    # =========================================================================
    # А. Несколько вопросов в одном сообщении
    # =========================================================================

    def _bot_part(self, train: bool) -> Tuple[str, str, dict]:
        cands = [b for b in BOT_PARTS if train or b[1]]
        tr, te, answers, key = self.pick(cands)
        return self.pick(tr if train else te), self.pick(answers), chk(*key.split(","))

    def _part(self, train: bool, skill: str) -> Tuple[str, str, dict]:
        """Один вопрос существующего навыка: (вопрос, короткий ответ, проверка)."""
        if skill == "bot":
            return self._bot_part(train)
        for _ in range(4):        # предпочтительно ответ из нескольких слов («Столица Франции — Париж.», а не «Париж.»)
            r = getattr(self, skill)(train, self.opp) if skill == "opposite" else getattr(self, skill)(train)
            q, a = r["turns"][0][1], r["turns"][1][1]
            if len(a.split()) >= 2:
                break
        c = dict(r["check"])
        # Короткий ключ (≤ 3 букв) сверяется только целым словом, поэтому «бел» не находит «белое». В старых
        # задачах «цвета предметов» так и осталось (чтобы цифры были сравнимы), а здесь ключ — полные формы.
        c["any"] = [k for k in r["check"]["any"] if k not in SHORT_COLOR_STEMS] + \
            [k + e for k in r["check"]["any"] if k in SHORT_COLOR_STEMS for e in ("ый", "ий", "ая", "яя", "ое", "ее", "ые", "ие")]
        return q, a, c

    def _parts(self, train: bool, k: int) -> List[Tuple[str, str, dict]]:
        """k частей-вопросов: train=True — обучающие формулировки, False — отложенные."""
        names, weights = zip(*MQ_SKILLS)
        for _ in range(20):
            skills = []
            while len(skills) < k:          # разные навыки: два вопроса про столицы — тоже можно, но реже
                s = self.rng.choices(names, weights)[0]
                if s not in skills or self.rng.random() < 0.15:
                    skills.append(s)
            parts = [self._part(train, s) for s in skills]
            qs = [p[0] for p in parts]
            ans = [p[1] for p in parts]
            keys_seen = [_norm(" ".join(p[2].get("any", []))) for p in parts]
            # запрет одной части не должен совпадать с ответом другой («птица» — и ответ, и запрет)
            clash = any(_overlap(" ".join(ans), w) for p in parts for w in p[2].get("none", []))
            # ответ не длиннее ~60 токенов (лимит генерации 64), вопросы и ответы не повторяются
            if not clash and len(set(qs)) == k and len(set(ans)) == k and len(set(keys_seen)) == k \
                    and sum(len(a) for a in ans) <= 150:
                return parts
        return parts

    def _join(self, qs: List[str], answers: List[str], train: bool) -> Tuple[str, str]:
        """Склейка вопросов в одно сообщение и ответов — в одну реплику."""
        k = len(qs)
        style = self.pick(MQ_JOINS_TRAIN if train else MQ_JOINS_TEST)
        ans = " ".join(answers)
        if style == "и ещё":
            msg = " ".join(qs[:-1]) + " " + self.pick(["И ещё: ", "И ещё "]) + low(qs[-1])
        elif style == "а также" and qs[0].endswith("?") and k == 2:
            msg = qs[0][:-1] + ", а также " + low(qs[1])
        elif style == "а ещё":
            msg = " ".join(qs[:-1]) + " А ещё " + low(qs[-1])
        elif style == "и":
            msg = " ".join(qs[:-1]) + " И " + low(qs[-1])
        elif style == "номера":
            sep = self.pick([") ", ". "])
            msg = " ".join(f"{i + 1}{sep}{q}" for i, q in enumerate(qs))
            ans = " ".join(f"{i + 1}{sep}{a}" for i, a in enumerate(answers))
        elif style == "перенос":            # в чате это перевод строки; в токенах — пробел (clean_turn)
            msg = "\n".join(low(q).rstrip("?.") if self.rng.random() < 0.5 else q for q in qs)
        elif style == "приветствие":
            g, ga = self.pick(GREETINGS_TRAIN if train else GREETINGS_TEST)
            msg, ans = g + " ".join(qs), ga + ans
        elif style == "вступление":
            msg = self.pick(MQ_LEADS_TRAIN if train else MQ_LEADS_TEST).format(k=MQ_COUNT_WORD[k]) + " ".join(qs)
        elif style == "кроме того":
            msg = " ".join(qs[:-1]) + " Кроме того, " + low(qs[-1])
        elif style == "во-первых":
            words = ["Во-первых, ", "Во-вторых, ", "В-третьих, "]
            msg = " ".join(words[i] + low(q) for i, q in enumerate(qs))
        elif style == "ещё вопрос":
            msg = " ".join(qs[:-1]) + " Ещё вопрос: " + low(qs[-1])
        else:
            msg = " ".join(qs)
        return msg, ans

    def multi_question(self, train: bool, heldout_parts: bool = False) -> dict:
        """2–3 вопроса в одном сообщении → ответы на все, по порядку, одной репликой. В проверке сообщение
        новое (отложенные способы склейки и сочетания), а части — в знакомых формулировках; отложенные
        формулировки самих частей — отдельная категория (multi_question_heldout)."""
        k = 2 if self.rng.random() < 0.6 else 3
        parts = self._parts(not heldout_parts, k)        # части — в знакомых формулировках (кроме heldout_parts)
        msg, ans = self._join([p[0] for p in parts], [p[1] for p in parts], train)
        src = "навык:несколько вопросов: " + ("отложенные формулировки частей" if heldout_parts
                                                 else "два" if k == 2 else "три")
        return row([("user", msg), ("bot", ans)], src, chk_all(*[p[2] for p in parts], order=True))

    def multi_question_heldout(self, train: bool) -> dict:
        """Только проверка: и склейка, и формулировки частей отложены (вдвойне новое сообщение)."""
        return self.multi_question(False, heldout_parts=True)

    def multi_question_fact(self, train: bool) -> dict:
        """Один из вопросов — о том, что пользователь рассказал раньше (или в этом же сообщении)."""
        names = NAMES_TRAIN if train else NAMES_TEST
        n = self.pick(names)
        other = self._parts(True, 1 if self.rng.random() < 0.7 else 2)
        if self.rng.random() < 0.5:          # знакомство раньше, вопрос «как меня зовут?» — среди других
            turns = [("user", self.pick([f"Меня зовут {n}.", f"Привет, я {n}.", f"Будем знакомы, я {n}."] if train
                                        else [f"Здравствуй, меня зовут {n}."])),
                     ("bot", self.pick([f"Приятно познакомиться, {n}!", f"Привет, {n}! Рад знакомству."]))]
            turns += self.distract(1)
            mine = (self.pick(["Как меня зовут?", "Ты помнишь, как меня зовут?", "Как моё имя?"]), f"Тебя зовут {n}.", chk(n))
            parts = other[:]
            parts.insert(self.rng.randrange(len(parts) + 1), mine)
            msg, ans = self._join([p[0] for p in parts], [p[1] for p in parts], train)
            return row(turns + [("user", msg), ("bot", ans)], "навык:несколько вопросов: с фактом из разговора",
                       chk_all(*[p[2] for p in parts], order=True))
        # знакомство в том же сообщении: «Меня зовут Оля. Как тебя зовут? Сколько будет 2 + 2?»
        intro = self.pick([f"Меня зовут {n}.", f"Я {n}.", f"Привет, я {n}!"] if train else [f"Моё имя — {n}."])
        bot_q = self._bot_part(True)
        parts = [bot_q] + other[:1]
        if self.rng.random() < 0.5:
            parts.reverse()
        msg = intro + " " + " ".join(p[0] for p in parts)
        ans = f"Приятно познакомиться, {n}! " + " ".join(p[1] for p in parts)
        return row([("user", msg), ("bot", ans)], "навык:несколько вопросов: с фактом из разговора",
                   chk_all(*[p[2] for p in parts], order=True))

    def one_question(self, train: bool) -> dict:
        """Контраст: вопрос ОДИН (с приветствием, вступлением или рассказом о себе) — и ответ один, без выдумок."""
        r = self.rng.random()
        if r < 0.35:                         # приветствие + один вопрос
            q, a, c = self._parts(True, 1)[0]
            g, ga = self.pick(GREETINGS_TRAIN if train else GREETINGS_TEST)
            ans = ga + a
            return row([("user", g + q), ("bot", ans)], "навык:несколько вопросов: один вопрос",
                       chk_all(c, max_words=len(ans.split()) + 4))
        if r < 0.55:                         # «У меня вопрос. …»
            q, a, c = self._parts(True, 1)[0]
            lead = self.pick(["У меня вопрос. ", "Ответь на вопрос: ", "Один вопрос: ", "Хочу спросить: "] if train
                             else ["Подскажи одну вещь. "])
            return row([("user", lead + (low(q) if lead.endswith(": ") else q)), ("bot", a)],
                       "навык:несколько вопросов: один вопрос", chk_all(c, max_words=len(a.split()) + 4))
        # рассказ о себе + встречный вопрос о боте
        names = NAMES_TRAIN if train else NAMES_TEST
        kind = self.pick(["name", "name", "city", "age", "job"])
        if kind == "name":
            n = self.pick(names)
            msg = self.pick([f"Меня зовут {n}. А тебя как?", f"Я {n}. А ты кто?", f"Меня зовут {n}. А тебя?",
                             f"Привет, я {n}! А как тебя зовут?"] if train else [f"Моё имя {n}. А твоё?"])
            ans = f"Приятно познакомиться, {n}! Меня зовут SLR-Net."
            c = chk("slr-net", none=["тебя зовут"])
        elif kind == "city":
            nom, prep = self.pick(CITIES_TRAIN if train else CITIES_TEST)
            v = v_prep(prep)
            msg = self.pick([f"Я живу {v} {prep}. А ты где живёшь?", f"Я из города {nom}. А ты откуда?"] if train
                            else [f"Я живу {v} {prep}. А ты?"])
            ans = f"{nom} — хороший город! А я живу в твоём телефоне или компьютере."
            c = chk("телефон", "компьютер", "устройств", none=["ты живешь"])
        elif kind == "age":
            a_ = self.rng.randint(7, 80)
            y = years_word(a_)
            msg = self.pick([f"Мне {a_} {y}. А тебе?", f"Мне {a_} {y}. А тебе сколько?"] if train
                            else [f"Мне уже {a_} {y}. А тебе сколько лет?"])
            ans = "А я совсем молодой: меня обучили недавно."
            c = chk("молод", "недавно", none=[str(a_)])
        else:
            nom, ins = self.pick(PROFESSIONS_TRAIN if train else PROFESSIONS_TEST)
            msg = self.pick([f"Я работаю {ins}. А ты кем работаешь?", f"Я {nom}. А ты?"] if train
                            else [f"По профессии я {nom}. А ты чем занимаешься?"])
            ans = "Интересная профессия! А я работаю собеседником."
            c = chk("собеседник", none=[ins, nom])
        return row([("user", msg), ("bot", ans)], "навык:несколько вопросов: один вопрос",
                   chk_all(c, max_words=len(ans.split()) + 4))

