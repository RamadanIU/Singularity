    def _q(self, kind: str, train: bool, fill: dict, table=FOLLOWUP_Q) -> str:
        tr, te = table[kind]
        q = self.pick(tr if train else te)
        return self._wrap(q.format(**fill), train)

    def _wrap(self, q: str, train: bool) -> str:
        """Больше формулировок в обучении (третья версия данных): «Слушай, а о чём он?», «О чём он, как думаешь?».
        Маленькая модель не переносит навык на формулировку, которой не видела; отложенные — без обёрток."""
        if not train or self.rng.random() < 0.5:
            return q
        if q.endswith("?") and self.rng.random() < 0.3 and "думаешь" not in q and "по-твоему" not in q.lower():
            return q[:-1] + self.pick([", как думаешь?", ", а?", ", скажи?", ", помнишь?"])
        return self.pick(CTX_Q_PREFIXES) + low(q)

    @staticmethod
    def _fill(g: str, kind: Optional[dict] = None) -> dict:
        p = dict(PRONOUNS[g])
        f = {**p, "Nom": cap(p["nom"]), "Он": cap(p["nom"]), "он": p["nom"], "вышел": past("вышел", g)}
        if kind:
            f.update(inf=kind["inf"], cond=kind["cond"],
                     obj=(kind["obj_pre"] + p["obj_v"]) if kind["obj_pre"] else p["acc"])
        return f

    def _echo(self, q: str) -> List[str]:
        """Эхо вопроса («В чём интересного?») — провал: дословный повтор вопроса запрещён проверкой."""
        t = _norm(q)
        t = re.sub(r"^(а|и|ну) ", "", t)
        return [t] if len(t.split()) >= 3 else []

    def _work(self, train: bool, long: bool = False, cat: Optional[str] = None, rare: bool = False) -> dict:
        """Вымышленное произведение и факты о нём, которые прозвучат в разговоре."""
        cat = cat or self.pick(list(WORK_KINDS))
        kind = WORK_KINDS[cat]
        for _ in range(30):
            if long:
                title = self.pick(WORK_TITLES_LONG_TEST)
            elif not train:
                # проверка: короткие названия из обычных слов («Синяя гора»), как и просит задание; названия из
                # редких слов («Дремучий флюгер») — отдельная категория (их mini2 искажает, как длинные имена)
                title = self._title(False) if rare else self.pick(WORK_TITLES[cat][1])
            elif self.rng.random() < 0.8:
                title = self._title(train)
            else:
                title = self.pick(WORK_TITLES[cat][0])
            plot = self._plot(train, cat)
            feat = self._feature(train)
            if not (_overlap(title, plot[1]) or _overlap(title, feat[1]) or _overlap(plot[0], feat[1])
                    or _overlap(feat[0], plot[1])):
                break
        g = kind["g"]
        male = self.rng.random() < 0.55
        if long:
            hname = self.pick(HERO_NAMES_LONG_TEST)
            male = True
        else:
            hname = self.pick((HERO_NAMES_M_TRAIN if male else HERO_NAMES_F_TRAIN) if train
                              else (HERO_NAMES_M_TEST if male else HERO_NAMES_F_TEST))
        role = self.pick(HERO_ROLES_M if male else HERO_ROLES_F)
        old, age_t, age_k = self.pick(AGE_FACTS)
        return {"cat": cat, "kind": kind, "g": g, "title": title, "plot": plot, "feature": feat,
                "hero": (f"{role} {hname}", hname.lower()), "age": (old, age_t.format(v=past("вышел", g)), age_k),
                "key": title}

    def _title(self, train: bool) -> str:
        """Название из прилагательного и существительного: «Тихая гавань», «Ледяные качели»."""
        while True:
            noun, g = self.pick(TITLE_NOUNS_TRAIN if train else TITLE_NOUNS_TEST)
            adj = self.pick(TITLE_ADJ_TRAIN if train else TITLE_ADJ_TEST)[GENDER_INDEX[g]]
            title = cap(adj) + " " + noun
            if not train or title not in HAND_TEST_TITLES:      # «Тихая река» отложена — в обучении её нет
                return title

    def _plot(self, train: bool, cat: str) -> Tuple[str, str]:
        """Сюжет: «про девочку, которая строит дом на дереве»; у игры — «нужно построить мост через реку»."""
        who, g, wkey = self.pick(PLOT_WHO_TRAIN if train else PLOT_WHO_TEST)
        sing, plur, inf, dkey = self.pick(PLOT_DO_TRAIN if train else PLOT_DO_TEST)
        if cat == "игра":
            return f"нужно {inf}", dkey
        return f"про {who}, {REL[g]} {plur if g == 'мн' else sing}", f"{wkey},{dkey}"

    def _feature(self, train: bool) -> Tuple[str, str]:
        """Чем интересно: «очень красивая музыка», «смешные шутки»."""
        noun, g, key = self.pick(FEAT_NOUNS_TRAIN if train else FEAT_NOUNS_TEST)
        adj = self.pick(FEAT_ADJ_TRAIN if train else FEAT_ADJ_TEST)[GENDER_INDEX[g]]
        return (("очень " if self.rng.random() < 0.5 else "") + adj + " " + noun), key

    def _mention(self, w: dict, train: bool) -> str:
        tmpl = self.pick(WORK_MENTIONS_TRAIN[w["cat"]] if train else WORK_MENTIONS_TEST[w["cat"]])
        p = PRONOUNS[w["g"]]
        return tmpl.format(T=w["title"], plot=w["plot"][0], Он=cap(p["nom"]), он=p["nom"])

    def _say(self, w: dict, slot: str, style: str = "plain") -> Tuple[str, str]:
        """Ответ про произведение, называющий его: (текст, ключи факта)."""
        k, T = w["kind"], w["title"]
        N, prep = k["nom"], k["prep"]
        if slot == "about":
            txt, keys = w["plot"]
            if w["cat"] == "игра":
                s = f"В игре «{T}» {txt}."
            else:
                s = f"{cap(N)} «{T}» — {txt}."
            return (("Конечно! " if style == "recall" else "") + s), keys
        if slot == "hero":
            txt, keys = w["hero"]
            return f"{'Конечно: г' if style == 'recall' else 'Г'}лавный герой в {prep} «{T}» — {txt}.", keys
        if slot == "feature":
            txt, keys = w["feature"]
            return f"{'Ещё в' if style == 'more' else 'В'} {prep} «{T}» {txt}.", keys
        if slot == "age":
            old, txt, keys = w["age"]
            return f"{N} «{T}» {txt}.", keys
        raise ValueError(slot)

    def _clause(self, w: dict, slot: str) -> Tuple[str, str]:
        """Факт как придаточное: «интересно то, что …»."""
        if slot == "about":
            txt, keys = w["plot"]
            lead = {"игра": "там ", "песня": "это песня "}.get(w["cat"], "это история ")
            return lead + txt, keys
        if slot == "feature":
            return "там " + w["feature"][0], w["feature"][1]
        if slot == "hero":
            return "главный герой там — " + w["hero"][0], w["hero"][1]
        raise ValueError(slot)

    def _answer_work(self, w: dict, qkind: str, facts_said: List[str], last_slot: Optional[str]) -> Tuple[str, str, str]:
        """(ответ, ключи факта для проверки, какой факт назван) на вопрос-продолжение о произведении."""
        k, T = w["kind"], w["title"]
        N, prep = k["nom"], k["prep"]
        if qkind in ("about", "recall_about"):
            a, keys = self._say(w, "about", "recall" if qkind == "recall_about" and self.rng.random() < 0.5 else "plain")
            return a, keys, "about"
        if qkind in ("hero", "recall_hero"):
            a, keys = self._say(w, "hero", "recall" if qkind == "recall_hero" and self.rng.random() < 0.5 else "plain")
            return a, keys, "hero"
        if qkind == "old":
            old, txt, keys = w["age"]
            return self._yes_old(old, self._last_q, f"{N} «{T}» {txt}."), keys, "age"
        if qkind == "more":
            left = [s for s in facts_said if s != last_slot and s != "age"]
            slot = self.pick(left)
            if slot == "feature":
                a, keys = self._say(w, "feature", "more")
            elif slot == "hero":
                a, keys = f"Ещё в {prep} «{T}» главный герой — {w['hero'][0]}.", w["hero"][1]
            else:
                a, keys = f"Ещё {N} «{T}» — {w['plot'][0]}." if w["cat"] != "игра" else \
                    f"Ещё в игре «{T}» {w['plot'][0]}.", w["plot"][1]
            return a, keys, slot
        open_slots = [s for s in facts_said if s in ("about", "feature", "hero")]
        slot = self.pick(open_slots)
        cl, _ = self._clause(w, slot)
        keys = ",".join(self._clause(w, s)[1] for s in open_slots)     # любой факт из разговора
        acc_obj = ("в " if k["obj_pre"] else "") + f"{k['acc']} «{T}»"
        if qkind == "interesting":
            a = self.pick([f"В {prep} «{T}» интересно то, что {cl}.", f"Самое интересное в {prep} «{T}» — то, что {cl}."])
        elif qkind == "opinion":
            a = f"Думаю, в {prep} «{T}» самое интересное то, что {cl}."
        elif qkind == "why":
            a = f"{cap(N)} «{T}» мне нравится, потому что {cl}."
        elif qkind == "recommend":
            a = f"Да, {acc_obj} стоит {k['inf']}: {cl}."
        elif qkind == "would":
            if "стоит" in self._last_q:
                again = " ещё раз" if "ещё раз" in self._last_q else ""
                a = f"Да, {acc_obj} стоит {k['inf']}{again}: {cl}."
            else:
                a = f"Да, я бы {k['cond']} {acc_obj}: {cl}."
        else:
            raise ValueError(qkind)
        return a, keys, slot

    def _work_dialogue(self, train: bool, n_follow: int, long: bool = False,
                       w: Optional[dict] = None) -> Tuple[List[Turn], dict, str, str]:
        """Пользователь рассказывает о произведении → бот реагирует → n_follow вопросов-продолжений."""
        w = w or self._work(train, long)
        fill = self._fill(w["g"], w["kind"])
        said = ["about"]
        msg = self._mention(w, train)
        extra = []
        if self.rng.random() < 0.55:
            extra.append("feature")
        if self.rng.random() < 0.45 and w["cat"] != "песня":        # у песни нет «главного героя»
            extra.append("hero")
        if self.rng.random() < 0.3:
            extra.append("age")
        self.rng.shuffle(extra)
        ext_txt = {"feature": lambda: self.pick(EXTRA_FACT_TRAIN).format(feature=w["feature"][0]),
                   "hero": lambda: self.pick(EXTRA_HERO_TRAIN).format(hero=w["hero"][0]),
                   "age": lambda: self.pick(EXTRA_AGE_TRAIN).format(Он=fill["Он"], он=fill["он"], age=w["age"][1])}
        turns: List[Turn] = []
        if extra and self.rng.random() < 0.5:                 # всё одной репликой
            msg += " " + " ".join(ext_txt[e]() for e in extra)
            turns += [("user", msg), ("bot", self.pick(WORK_REACTIONS))]
        else:
            if extra and self.rng.random() < 0.4:
                turns += [("user", msg), ("bot", self.pick(WORK_REACTIONS_Q)),
                          ("user", self.pick(USER_LIKED) + " " + ext_txt[extra[0]]()), ("bot", self.pick(WORK_REACTIONS))]
                rest = extra[1:]
            else:
                turns += [("user", msg), ("bot", self.pick(WORK_REACTIONS))]
                rest = extra
            for e in rest:
                turns += [("user", ext_txt[e]()), ("bot", self.pick(["Понятно!", "Интересно!", "Здорово!", "Ясно."]))]
        said += extra
        # вопросы-продолжения: только о том, что прозвучало
        kinds = ["recall_about", "would", "opinion"]
        if "hero" in said:
            kinds.append("recall_hero")
        if "age" in said:
            kinds.append("old")
        last_slot = None
        a = keys = ""
        q = ""
        for i in range(n_follow):
            avail = [x for x in kinds if not (x == "more" and len([s for s in said if s not in ("age", last_slot)]) == 0)]
            if i > 0 and len([s for s in said if s not in ("age", last_slot)]) > 0:
                avail.append("more")
            qk = self.pick(avail)
            q = self._q(qk, train, fill)
            self._last_q = q
            a, keys, last_slot = self._answer_work(w, qk, said, last_slot)
            turns += [("user", q), ("bot", a)]
            if qk in kinds and qk != "more" and self.rng.random() < 0.7:
                kinds.remove(qk)
                if not kinds:
                    kinds = ["would"]
        return turns, w, q, keys

    def _work_check(self, w: dict, keys: str, q: str, none: Sequence[str] = ()) -> dict:
        return chk_all(chk(*w["key"].split(",")), chk(*keys.split(",")), none=list(none) + self._echo(q))

