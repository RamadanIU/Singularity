    # ---------- бот сам назвал известное произведение или город
    def _famous_answer(self, f: tuple, qk: str, q: str) -> Tuple[str, str, str]:
        cat, T, tkey, facts = f
        k = WORK_KINDS[cat]
        N, prep = k["nom"], k["prep"]
        acc_obj = ("в " if k["obj_pre"] else "") + f"{k['acc']} «{T}»"
        if qk == "about":
            self._said.add("about")
            txt, keys = facts["about"]
            return (f"В игре «{T}» {txt}." if cat == "игра" else f"{cap(N)} «{T}» — {txt}."), keys, "about"
        if qk == "hero":
            self._said.add("hero")
            txt, keys = facts["hero"]
            return f"Главный герой в {prep} «{T}» — {txt}.", keys, "hero"
        if qk == "old":
            txt, keys = facts["age"]
            m = re.search(r"\d{4}", txt)
            old = int(m.group()) < 2000 if m else True
            return self._yes_old(old, q, f"{N} «{T}» {txt}."), keys, "age"
        if qk == "interesting":
            self._said.add("feature")
            txt, keys = facts["feature"]
            return self.pick([f"В {prep} «{T}» интересно то, что там {txt}.",
                              f"Самое интересное в {prep} «{T}» — то, что там {txt}."]), keys, "feature"
        if qk == "more":
            left = [s for s in ("feature", "feature2", "hero", "about") if s in facts and s not in self._said]
            slot = self.pick(left or ["feature"])
            self._said.add(slot)
            txt, keys = facts[slot]
            if slot in ("feature", "feature2"):
                return f"Ещё в {prep} «{T}» {txt}.", keys, slot
            if slot == "hero":
                return f"Ещё в {prep} «{T}» главный герой — {txt}.", keys, slot
            return (f"Ещё в игре «{T}» {txt}." if cat == "игра" else f"Ещё {N} «{T}» — {txt}."), keys, slot
        if qk == "why":
            txt, keys = facts["why"]
            return f"{cap(N)} «{T}» мне нравится, потому что {txt}.", keys, "why"
        if qk == "recommend":
            txt, keys = facts["why"]
            return f"Да, {acc_obj} стоит {k['inf']}: {txt}.", keys, "why"
        raise ValueError(qk)

    def ctx_famous_bot(self, train: bool, n_follow: int = 1, src: str = "навык:контекст: бот назвал") -> dict:
        """Бот назвал известное произведение (любимое — как в ручных диалогах, или совет) → вопрос о нём.
        Сюда же — пример владельца: «Какой твой любимый фильм?» → … → «А что в нём интересного?».
        В проверке нужный факт всегда звучит в реплике бота: проверяется умение взять его из разговора, а не
        знание произведения, которого модель не видела. В обучении — в половине диалогов (иначе ответ — из памяти)."""
        if self.rng.random() < 0.3:
            return self.ctx_city_bot(train, n_follow, src)
        pool = FAMOUS_WORKS_TRAIN if train else FAMOUS_WORKS_TEST
        f = self.pick(pool)
        cat, T, tkey, facts = f
        k = WORK_KINDS[cat]
        asks_tr, asks_te = FAMOUS_ASK[cat]
        fav = PERSONA_FAVORITE.get(cat) == T
        asks = [a for a in (asks_tr if train else asks_te) if fav or "любим" not in a]
        if fav and train and self.rng.random() < 0.6:
            asks = [a for a in asks if "любим" in a] or asks
        ask = self.pick(asks)
        liked = "любим" in ask or "нравится" in ask
        if liked:
            base = self.pick([f"Мой любимый {k['nom']} — «{T}»." if k["g"] == "м" else f"Моя любимая {k['nom']} — «{T}».",
                              f"Мне нравится «{T}»."])
        else:
            verb = {"фильм": "Посмотри", "мультфильм": "Посмотри", "книга": "Почитай", "игра": "Поиграй в"}[cat]
            base = f"{verb} «{T}»."
        fill = self._fill(k["g"], k)
        kinds = ["interesting", "about", "why" if liked else "recommend"]
        if "hero" in facts:
            kinds.append("hero")
        if "age" in facts:
            kinds.append("old")
        with_facts = (not train) or self.rng.random() < 0.5
        self._said = set()
        qa: List[Turn] = []
        used: List[str] = []
        a = keys = q = ""
        for i in range(n_follow):
            more_left = [s for s in ("feature", "feature2", "hero", "about") if s in facts and s not in self._said]
            avail = kinds + (["more"] if i > 0 and more_left else [])
            if not avail:
                break
            qk = self.pick(avail)
            q = self._q(qk, train, fill)
            a, keys, slot = self._famous_answer(f, qk, q)
            qa += [("user", q), ("bot", a)]
            used.append(slot)
            if qk in kinds:
                kinds.remove(qk)
        first = base
        if with_facts:                                 # факты для этих вопросов — в первой реплике бота
            sent = {"about": (f"Это {k['nom']} {facts['about'][0]}" if cat != "игра" else f"Там {facts['about'][0]}"),
                    "hero": f"Главный герой там — {facts['hero'][0]}" if "hero" in facts else "",
                    "feature": f"Там {facts['feature'][0]}",
                    "feature2": f"Там {facts['feature2'][0]}" if "feature2" in facts else "",
                    "why": cap(facts["why"][0]),
                    "age": f"{cap(PRONOUNS[k['g']]['nom'])} {facts['age'][0]}" if "age" in facts else ""}
            extra = [sent[s] for s in dict.fromkeys(used) if sent.get(s)]
            first = base + "".join(f" {x}." for x in extra)
        turns: List[Turn] = [("user", ask), ("bot", first)] + qa
        return row(turns, src, chk_all(chk(*tkey.split(",")), chk(*keys.split(",")), none=self._echo(q)))

    def ctx_city_bot(self, train: bool, n_follow: int = 1, src: str = "навык:контекст: бот назвал") -> dict:
        c = self.pick(CITIES_CTX_TRAIN if train else CITIES_CTX_TEST)
        nom, acc, prep, key, loc, sight, extra, k_loc, k_sight, k_extra = c
        ask = self.pick(CITY_ASK[0] if train else CITY_ASK[1])
        v = v_prep(prep)
        base = f"Мне нравится {nom}." if "нравится" in ask else \
            self.pick([f"Съезди {v_prep(acc)} {acc}.", f"Я бы посоветовал {acc}."])
        kinds = ["loc", "sight"]
        said_more = False
        qa: List[Turn] = []
        used: List[str] = []
        a = keys = q = ""
        for i in range(n_follow):
            opts = kinds + (["more"] if i > 0 and not said_more else [])
            if not opts:
                break
            qk = self.pick(opts)
            q = self._wrap(self.pick(CITY_Q[qk][0] if train else CITY_Q[qk][1]), train)
            if qk == "loc":
                a, keys, slot = self.pick([f"{nom} находится {loc}.", f"{nom} стоит {loc}."]), k_loc, "loc"
            elif qk == "sight":
                a, keys, slot = f"{cap(v)} {prep} стоит посмотреть {sight}.", k_sight, "sight"
            elif "sight" in used:
                a, keys, slot = f"Ещё {v} {prep} {extra}.", k_extra, "extra"
                said_more = True
            else:
                a, keys, slot = f"Ещё {v} {prep} можно посмотреть {sight}.", k_sight, "sight"
                said_more = True
            qa += [("user", q), ("bot", a)]
            used.append(slot)
            if qk in kinds:
                kinds.remove(qk)
        first = base
        if (not train) or self.rng.random() < 0.5:
            sent = {"loc": f"Это город {loc}", "sight": f"Там стоит посмотреть {sight}", "extra": f"Там {extra}"}
            first = base + "".join(f" {sent[s]}." for s in dict.fromkeys(used))
        elif self.rng.random() < 0.5:
            first = base[:-1] + f": там {extra}."
        turns: List[Turn] = [("user", ask), ("bot", first)] + qa
        return row(turns, src, chk_all(chk(*key.split(",")), chk(*keys.split(",")), none=self._echo(q)))

