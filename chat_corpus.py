def explain(w: str, info: dict, rng: random.Random, mentioned: bool = False) -> str:
    """Объяснение слова от пользователя. mentioned=True — слово уже звучало («Это ...»)."""
    pron = PRON[info["g"]]
    head = "Это" if mentioned and rng.random() < 0.6 else f"{cap(w)} — это"
    such, self_ = {"м": ("такой", "сам"), "ж": ("такая", "сама"), "с": ("такое", "само")}[info["g"]]
    r = rng.random()
    if r < 0.3:
        s = f"{head} {info['size']} {info['cat']} {info['color']} цвета. {cap(pron)} {info['verb']} {info['place']}."
    elif r < 0.5:
        s = f"{head} {info['cat']}: {info['size']}, {info['color']} цвета, {info['verb']} {info['place']}."
    elif r < 0.65:
        s = f"{head} {info['size']} {info['cat']}, {pron} {info['verb']} {info['place']}. И {pron} {info['color']} цвета."
    elif r < 0.85:
        s = f"{head} {such} {info['cat']} {info['color']} цвета. {cap(info['verb'])} {info['place']}, {self_} {info['size']}."
    else:                                   # сначала место, слово — в конце
        s = f"{cap(info['place'])} {info['verb']} {info['size']} {info['cat']} — {w}. {cap(pron)} {info['color']} цвета."
    if info["purpose"]:
        s += f" {cap(pron)} нужен, чтобы {info['purpose']}."
    return s


