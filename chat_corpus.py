def chk_all(*parts: dict, order: bool = False, none: Sequence[str] = (), max_words: Optional[int] = None) -> dict:
    """Составная проверка: должны пройти ВСЕ части (order=True — и найтись в ответе в том же порядке);
    none — запрещённое во всём ответе; max_words — ответ не длиннее (не выдумывать лишнего)."""
    c: dict = {"all": [p for p in parts if p]}
    if order:
        c["order"] = True
    if none:
        c["none"] = [w for w in none if w]
    if max_words:
        c["max_words"] = int(max_words)
    return c


def low(s: str) -> str:
    """Первая буква — строчная (но «США», «SLR-Net» не трогаем)."""
    return s if len(s) > 1 and s[1:2].isupper() else s[:1].lower() + s[1:]


def _norm(s: str) -> str:
    """Как norm_text в train_chat.py: без регистра, «ё» → «е», без знаков."""
    s = re.sub(r"[^\w ]+", "", s.lower().replace("ё", "е"))
    return re.sub(r"\s+", " ", s).strip()


