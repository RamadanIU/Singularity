    # ---------- счёт
    def arithmetic(self, train: bool) -> dict:
        r = self.rng.random()
        if r < 0.45:
            a, b = self.rng.randint(0, 10), self.rng.randint(0, 10)
            op, res, sym, word = "плюс", a + b, "+", "плюс"
        elif r < 0.8:
            a = self.rng.randint(0, 20)
            b = self.rng.randint(0, a)
            op, res, sym, word = "минус", a - b, "-", "минус"
        else:
            a, b = self.rng.randint(2, 9), self.rng.randint(2, 9)
            op, res, sym, word = "умножить на", a * b, "×", "умножить на"
        if self.rng.random() < 0.4 and max(a, b) <= 19:
            q = (self.pick([f"Сколько будет {num_word(a)} {op} {num_word(b)}?", f"{cap(num_word(a))} {op} {num_word(b)} — сколько?"])
                 if train else f"Посчитай, пожалуйста: {num_word(a)} {op} {num_word(b)}.")
            ans = f"{cap(num_word(a))} {op} {num_word(b)} — {num_word(res)}."
        else:
            forms = [f"Сколько будет {a} {op} {b}?", f"{a} {op} {b} — сколько?", f"Посчитай: {a} {op} {b}."]
            if sym != "×":
                forms.append(f"{a} {sym} {b} = ?")
                forms.append(f"Сколько будет {a} {sym} {b}?")
            test = {"плюс": f"Сколько получится, если к {a} прибавить {b}?",
                    "минус": f"Сколько получится, если от {a} отнять {b}?"}.get(op, f"Сколько получится, если {a} умножить на {b}?")
            q = self.pick(forms) if train else test
            ans = self.pick([f"{a} {op} {b} будет {res}.", f"{res}." if sym == "×" else f"{a} {sym} {b} = {res}."])
        return row([("user", q), ("bot", ans)], "шаблон:счёт", chk(str(res), num_word(res)))

