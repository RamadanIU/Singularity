# Сколько диалогов в эпоху и сколько проверочных задач (на отложенных значениях и формулировках)
CONTEXT_PLAN = [
    ("multi_question", 8000, 80), ("multi_question_fact", 1500, 20), ("one_question", 3000, 30),
    ("ctx_work_user", 5500, 50), ("ctx_famous_bot", 1000, 30), ("ctx_misc_user", 3000, 30),
    ("ctx_chain", 2000, 25), ("ctx_you_too", 1500, 20), ("ctx_topic_shift", 1500, 30), ("ctx_no_topic", 1200, 15),
    ("ctx_long_names", 0, 15), ("multi_question_heldout", 0, 40), ("ctx_rare_titles", 0, 25),
]


def build_context_skills(rng: random.Random, filler: List[List[Turn]], scale: float = 1.0,
                         augment_p: float = 0.3) -> Dict[str, List[dict]]:
    """Навыки А и Б: обучающие диалоги, отложенные диалоги (для ошибки) и задачи с проверкой."""
    g = ContextGen(rng, filler)
    train, val, probes = [], [], []

    def fits(fn, train_: bool) -> dict:
        # диалог должен влезть в окно mini2 (256 токенов): иначе начало обрежется и пропадёт то, о чём спрашивают
        while True:
            r = fn(train_)
            if sum(len(t[1]) + 3 for t in r["turns"]) <= MAX_DIALOGUE_CHARS:
                return r

    for name, n_train, n_test in CONTEXT_PLAN:
        fn = getattr(g, name)
        for _ in range(int(n_train * scale)):
            train.append(fits(fn, True))
        for i in range(n_test):
            p = fits(fn, False)
            if i % 4 == 0:
                val.append(p)
            probes.append({"cat": p["src"], "turns": p["turns"][:-1], "check": p["check"]})
    train = [{**r, "turns": [list(t) for t in r["turns"]]} for r in train]
    augment(train, rng, augment_p)
    return {"train": train, "val": val, "probes": probes}


