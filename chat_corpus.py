Turn = Tuple[str, str]


def row(turns: Sequence[Turn], src: str, check: Optional[dict] = None, w: float = 1.0) -> dict:
    r = {"turns": [list(t) for t in turns], "src": src}
    if check:
        r["check"] = check
    if w != 1.0:
        r["w"] = w
    return r


def chk(*words, none: Sequence[str] = (), tail: Optional[str] = None) -> dict:
    """Проверка ответа: есть хотя бы одно из words и нет ни одного из none. tail — проверять только текст
    после последнего вхождения этого слова (вывод рассуждения: «... Значит, выше всех Аня»)."""
    c = {"any": [w for w in words if w]}
    if none:
        c["none"] = list(none)
    if tail:
        c["tail"] = tail
    return c


def cap(s: str) -> str:
    return s[:1].upper() + s[1:]


