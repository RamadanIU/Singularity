def reference_turn(word: str, definition: str, question: str) -> str:
    """Реплика пользователя со справкой из словаря. Тот же формат подставляет train_chat.py chat --dictionary."""
    return f"Справка: {cap(word)} — {definition} {question}"


def nonce_gender(w: str) -> str:
    return "ж" if w.endswith("а") else "м"


def nonce_plural(w: str) -> str:
    """клуфа → клуфы, бармук → бармуки, стипос → стипосы."""
    stem = w[:-1] if w.endswith("а") else w
    return stem + ("и" if stem[-1] in "кгхжшщч" else "ы")


def nonce_gen(w: str) -> str:
    """Родительный падеж: клуфа → клуфы, стипос → стипоса."""
    return nonce_plural(w) if w.endswith("а") else w + "а"


