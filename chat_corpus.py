def num_word(n: int) -> str:
    if n < 20:
        return NUM_WORDS[n]
    if n == 100:
        return "сто"
    t, u = divmod(n, 10)
    return TENS[t] + ("" if u == 0 else " " + NUM_WORDS[u])


def years_word(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return "год"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "года"
    return "лет"


