def plural(n: int, forms: Tuple[str, str, str]) -> str:
    """1 яблоко, 2 яблока, 5 яблок."""
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return forms[1]
    return forms[2]


