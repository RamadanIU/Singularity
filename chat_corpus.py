class SeedBlock:
    def __init__(self, tag: str, questions: List[str], answers: List[str], check: Optional[List[str]],
                 none: Optional[List[str]] = None):
        self.tag, self.questions, self.answers, self.check, self.none = tag, questions, answers, check, none or []


def _split(s: str) -> List[str]:
    return [p.strip() for p in s.split(" | ") if p.strip()]


def parse_seed_text(text: str) -> Tuple[List[SeedBlock], List[Tuple[str, List[Turn]]]]:
    singles: List[SeedBlock] = []
    multis: List[Tuple[str, List[Turn]]] = []
    tag = "разное"
    for chunk in re.split(r"\n\s*\n", text):
        lines = [ln.rstrip() for ln in chunk.splitlines()]
        lines = [ln for ln in lines if ln.strip() and not ln.lstrip().startswith("# ")]
        body = []
        for ln in lines:
            if ln.startswith("## "):
                tag = ln[3:].strip()
            elif not ln.startswith("#"):
                body.append(ln)
        if not body:
            continue
        if body[0].startswith(("> ", "< ")):
            turns = []
            for ln in body:
                if ln.startswith("> "):
                    turns.append(("user", ln[2:].strip()))
                elif ln.startswith("< "):
                    turns.append(("bot", ln[2:].strip()))
                else:
                    raise ValueError(f"Строка многоходового диалога должна начинаться с «>» или «<»: {ln!r}")
            multis.append((tag, turns))
            continue
        qs = _split(body[0])
        answers = check = None
        none: List[str] = []
        for ln in body[1:]:
            if ln.startswith("=> "):
                answers = _split(ln[3:])
            elif ln.startswith("?= "):
                check = [w.strip() for w in ln[3:].split(",") if w.strip()]
            elif ln.startswith("?! "):
                none = [w.strip() for w in ln[3:].split(",") if w.strip()]
        if not answers:
            raise ValueError(f"У блока нет ответа «=>»: {body[0]!r}")
        singles.append(SeedBlock(tag, qs, answers, check, none))
    return singles, multis


def load_seeds(seed_dir: Path = SEED_DIR):
    singles, multis = [], []
    for path in sorted(seed_dir.glob("seed_*.txt")):
        s, m = parse_seed_text(path.read_text(encoding="utf-8"))
        singles += s
        multis += m
    return singles, multis


